#!/usr/bin/env python3
"""Regenerates src/ui/icons.slint (the library's `Icon` component) from res/icons/*.svg.

Slint resolves `@image-url` at compile time, so the component lists every icon literally. The
paths are relative to the extracted library directory, where res/ sits next to icons.slint.
Run after adding or removing an icon; CI fails when the file is out of date (--check).
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "ui" / "icons.slint"


def render() -> str:
    names = sorted(p.stem for p in (ROOT / "res" / "icons").glob("*.svg"))
    lines = [
        "// Generated by scripts/gen-icons.py from res/icons; do not edit.",
        "",
        'import { Theme } from "services/theme.slint";',
        "",
        "// One of SlintLu's stroke icons by name, tinted with `color`. Names: "
        + ", ".join(names)
        + ". Unknown names show \"info\".",
        "export component Icon inherits Image {",
        "    // The icon's file name in res/icons, without \".svg\".",
        "    in property <string> name;",
        "    // The stroke colour.",
        "    in property <color> color: Theme.text;",
        "    colorize: root.color;",
        "    image-fit: contain;",
        "    width: 20px;",
        "    height: 20px;",
        "    source:",
    ]
    lines += [f'        root.name == "{n}" ? @image-url("res/icons/{n}.svg") :' for n in names]
    lines += ['        @image-url("res/icons/info.svg");', "}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != text:
            sys.exit("src/ui/icons.slint is out of date: run scripts/gen-icons.py")
        return
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
