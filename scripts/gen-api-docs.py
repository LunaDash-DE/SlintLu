#!/usr/bin/env python3
"""Generates docs/API.md from the comments in the @slintlu library (src/ui/**/*.slint).

Run `just api-docs`; CI fails when the committed file is out of date.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
UI = ROOT / "src" / "ui"
OUT = ROOT / "docs" / "API.md"

ITEM = re.compile(r"^export (global|struct|enum|component) ([\w-]+)(?: inherits (\w+))?")
MEMBER = re.compile(
    r"^\s*(?:(in|out|in-out) property <([^>]+)> ([\w-]+)(?:\s*:\s*([^;]+))?;"
    r"|(pure )?callback ([\w-]+)\(([^)]*)\)(?:\s*->\s*([^;]+))?;"
    r"|([\w-]+)\s*:\s*([^,]+),"
    r"|([\w-]+),)"
)


def parse(path):
    items, comments, current = [], [], None
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if line.startswith("//"):
            comments.append(line[2:].strip())
            continue
        match = ITEM.match(line)
        if match:
            kind, name, base = match.groups()
            current = {"kind": kind, "name": name, "base": base, "doc": " ".join(comments), "members": []}
            items.append(current)
            comments = []
            continue
        if current and line.startswith("}") and raw.startswith("}"):
            current = None
            comments = []
            continue
        member = MEMBER.match(raw) if current else None
        if member:
            g = member.groups()
            doc = " ".join(comments)
            if g[2] and current["kind"] == "component" and g[0] == "out":
                pass  # internal plumbing of the base components
            elif g[2]:
                access = {"in": "read", "out": "read", "in-out": "read / write"}[g[0]]
                if current["kind"] == "component":
                    access = "set"
                default = f" = `{g[3].strip()}`" if g[3] else ""
                current["members"].append((f"`{g[2]}`", f"`{g[1]}`", access + default, doc))
            elif g[5]:
                ret = f" → `{g[7].strip()}`" if g[7] else ""
                current["members"].append((f"`{g[5]}({g[6]})`", "callback" + ret, "call", doc))
            elif g[8] and current["kind"] == "struct":
                current["members"].append((f"`{g[8]}`", f"`{g[9].strip()}`", "", doc))
            elif g[10] and current["kind"] == "enum":
                current["members"].append((f"`{g[10]}`", "", "", doc))
        if line and not line.startswith("//"):
            comments = []
    return items


def render(items):
    out = [
        "# `@slintlu` API reference",
        "",
        "<!-- Generated by scripts/gen-api-docs.py from src/ui; do not edit by hand. -->",
        "",
        "```slint",
        'import { PanelWindow, Shell, Clock, Theme } from "@slintlu";',
        "```",
        "",
        "Globals are filled in by SlintLu; *read* properties are set by the runtime, *read / write*",
        "ones may also be assigned by the shell, and callbacks are implemented natively.",
        "",
    ]
    order = {"component": 0, "global": 1, "struct": 2, "enum": 3}
    titles = {"component": "Components", "global": "Globals", "struct": "Structs", "enum": "Enums"}
    section = None
    for item in sorted(items, key=lambda i: (order[i["kind"]], i["name"])):
        if item["name"] == "SlintLuRuntime":
            continue
        if section != item["kind"]:
            section = item["kind"]
            out += [f"## {titles[section]}", ""]
        base = f" (inherits `{item['base']}`)" if item["base"] else ""
        out += [f"### {item['name']}{base}", ""]
        if item["doc"]:
            out += [item["doc"], ""]
        if item["members"]:
            out += ["| Member | Type | Access | Description |", "|---|---|---|---|"]
            for name, ty, access, doc in item["members"]:
                out.append(f"| {name} | {ty} | {access} | {doc.replace('|', '\\|')} |")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    items = [item for path in sorted(UI.rglob("*.slint")) for item in parse(path)]
    text = render(items)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("docs/API.md is out of date: run `just api-docs`")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(items)} items)")


main()
